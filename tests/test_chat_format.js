const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('ui/app.js','utf8');
const start=source.indexOf('function mdLite('),end=source.indexOf('function fmtBytes',start);
const ctx={esc:s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]))};
vm.createContext(ctx);vm.runInContext(source.slice(start,end),ctx);
const render=ctx.mdLite;
assert(render('- Width: **3000 mm**\n- Depth: 450 mm').includes('<ul><li>'));
assert(render('| Field | Value |\n| --- | --- |\n| Depth | 450 mm |').includes('<td>450 mm</td>'));
const tableWithCitedCell='| ITEM | LEVEL | AREA |\n|---:|---|---:|\n| 1 | Basement 1 [SOURCE: drawing.pdf | PAGE 1] | 32,031.40 sqm |';
const citedTableHtml=render(tableWithCitedCell);
assert(citedTableHtml.includes('<table>'));
assert(citedTableHtml.includes('<td>32,031.40 sqm</td>'));
assert(citedTableHtml.includes('<summary>Source · page 1</summary>'));
const citation='[SOURCE: drawing.pdf | PAGE 1]';
assert(render(citation).includes(citation));
assert(render(citation).includes('<summary>Source · page 1</summary>'));
assert(!render(citation).includes('<details open'));
assert(render('REVIEW_REQUIRED: approval is not established.').includes('REVIEW_REQUIRED: approval is not established.'));
assert(!render('<img src=x onerror=alert(1)>').includes('<img'));
assert(render('```\n<script>bad()</script>\n```').includes('&lt;script&gt;'));
assert(render('1. Check source\n2. Retain uncertainty').includes('<ol>'));
console.log('Chat formatting checks passed');
